"""Prompt-injection harness — Inv-12 / §8.11.

Labels content by trust level so nodes can enforce the policy boundary:
untrusted content (customer-supplied text, retrieved documents, menu data)
is NEVER allowed to grant tools or change authorization, regardless of what
the text says.

Design:
- Every piece of text flowing into the LLM is wrapped in a ``LabeledContent``
  that carries its ``TrustLevel``.
- ``is_tool_invocation_permitted`` is the core Inv-12 decision point: a tool
  invocation is permitted only when (a) the source is NOT ``UNTRUSTED``, and
  (b) the tool name appears in the ``ToolAllowlist`` derived from the verified
  ``TenantContext``.
- ``ToolAllowlist`` is immutable after construction — there is no mutation API,
  so no code path can expand the allowlist at runtime.
"""

from __future__ import annotations

from enum import Enum
from typing import TYPE_CHECKING

from pydantic import BaseModel, Field


if TYPE_CHECKING:
    from cordia_agent.safety.tenant_context import TenantContext


class TrustLevel(str, Enum):
    """Trust classification for a piece of content (§8.11).

    SYSTEM       — generated by this process (system prompt, policy rules).
    TOOL_RESULT  — returned by a verified tool invocation.
    UNTRUSTED    — customer speech, retrieved text, external data, menus, etc.
    """

    SYSTEM = "system"
    TOOL_RESULT = "tool_result"
    UNTRUSTED = "untrusted"


class LabeledContent(BaseModel):
    """A piece of text tagged with its trust level.

    ``extra="forbid"`` ensures no stray fields can sneak through boundaries.
    """

    model_config = {"extra": "forbid"}

    trust: TrustLevel = Field(
        description="Trust level of this content fragment (§8.11)."
    )
    text: str = Field(description="The raw text content.")


def label_system(text: str) -> LabeledContent:
    """Wrap *text* as SYSTEM-trusted content (generated by this process)."""
    return LabeledContent(trust=TrustLevel.SYSTEM, text=text)


def label_tool_result(text: str) -> LabeledContent:
    """Wrap *text* as TOOL_RESULT-trusted content (returned by a verified tool call)."""
    return LabeledContent(trust=TrustLevel.TOOL_RESULT, text=text)


def label_untrusted(text: str) -> LabeledContent:
    """Wrap *text* as UNTRUSTED content (customer speech, retrieved data, menus, etc.)."""
    return LabeledContent(trust=TrustLevel.UNTRUSTED, text=text)


class ToolAllowlist:
    """Immutable set of tool names the tenant is authorised to invoke (Inv-12).

    Constructed once from the verified ``TenantContext.allowed_policy_ids``; has
    no mutation API so no code path can expand the allowlist at runtime.
    """

    def __init__(self, allowed_tool_names: list[str] | frozenset[str]) -> None:
        self._allowed: frozenset[str] = frozenset(allowed_tool_names)

    @classmethod
    def from_tenant_context(cls, ctx: TenantContext) -> ToolAllowlist:
        """Build an allowlist from a verified ``TenantContext``'s allowed_policy_ids."""
        return cls(ctx.allowed_policy_ids)

    def is_allowed(self, tool_name: str) -> bool:
        """Return True iff *tool_name* appears in the allowlist."""
        return tool_name in self._allowed


def is_tool_invocation_permitted(
    tool_name: str,
    *,
    allowlist: ToolAllowlist,
    source: LabeledContent | TrustLevel,
) -> bool:
    """Core Inv-12 decision: may *tool_name* be invoked given *source* trust?

    Returns False immediately when *source* is UNTRUSTED — untrusted-sourced
    requests can NEVER invoke tools, regardless of the allowlist (§8.11).
    Otherwise delegates to ``allowlist.is_allowed(tool_name)``.

    Args:
        tool_name: The name of the tool being requested.
        allowlist: The tenant's immutable tool allowlist (from verified context).
        source: The ``LabeledContent`` or ``TrustLevel`` of the requesting content.

    Returns:
        True only when the source is trusted AND the tool is on the allowlist.
    """
    trust = source.trust if isinstance(source, LabeledContent) else source
    if trust is TrustLevel.UNTRUSTED:
        return False
    return allowlist.is_allowed(tool_name)

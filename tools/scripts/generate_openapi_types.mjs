#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

function usage() {
  console.error("Usage: node generate_openapi_types.mjs <input-openapi-json> <output-ts-file>");
  process.exit(1);
}

const [inputPathArg, outputPathArg] = process.argv.slice(2);

if (!inputPathArg || !outputPathArg) {
  usage();
}

const inputPath = path.resolve(process.cwd(), inputPathArg);
const outputPath = path.resolve(process.cwd(), outputPathArg);

if (!fs.existsSync(inputPath)) {
  throw new Error(`OpenAPI document not found: ${inputPath}`);
}

const schema = JSON.parse(fs.readFileSync(inputPath, "utf8"));
const generatedAst = await openapiTS(schema, {
  rootTypes: true,
  rootTypesNoSchemaPrefix: true,
  defaultNonNullable: true,
  propertiesRequiredByDefault: true,
  enumValues: true,
});
const generatedTypes = astToString(generatedAst);

const outputDir = path.dirname(outputPath);
fs.mkdirSync(outputDir, { recursive: true });

const header = `// <auto-generated>
// This file was generated by openapi-typescript from the exported OpenAPI document.
// Do not modify this file directly - changes will be overwritten.
//
// Source document: libs/api-contract/openapi/v1.json
// </auto-generated>

`;

fs.writeFileSync(outputPath, `${header}${generatedTypes}`);
console.log(`TypeScript OpenAPI types generated successfully at ${outputPath}`);
